y_true = []
y_pred = []

for text in danger_samples:
    status, _ = analyze_text(text)
    predicted = "danger" if status == "danger_keyword" else "safe"
    y_true.append("danger")
    y_pred.append(predicted)

for text in safe_samples:
    status, _ = analyze_text(text)
    predicted = "danger" if status == "danger_keyword" else "safe"
    y_true.append("safe")
    y_pred.append(predicted)


acc = accuracy_score(y_true, y_pred)
prec = precision_score(y_true, y_pred, pos_label="danger")
rec = recall_score(y_true, y_pred, pos_label="danger")
f1 = f1_score(y_true, y_pred, pos_label="danger")

print("Accuracy:", acc)
print("Precision:", prec)
print("Recall:", rec)
print("F1-score:", f1)
print("\nDetailed Report:\n")
print(classification_report(y_true, y_pred))

cm = confusion_matrix(y_true, y_pred, labels=["danger","safe"])
